// The daemon owns validateManifest (daemon/src/core/gamepacks/manifest.ts, dependency-free).
// This copies it into the SDK so `hosty-pack validate` applies exactly the same rules.
// Run: npm run sync-validator   (a daemon test fails when the copy is stale)
const fs = require('node:fs');
const path = require('node:path');

const source = path.resolve(__dirname, '../../../daemon/src/core/gamepacks/manifest.ts');
const target = path.resolve(__dirname, '../src/validate.ts');
const banner = '// GENERATED by scripts/sync-validator.js from daemon/src/core/gamepacks/manifest.ts. Do not edit.\n';
fs.writeFileSync(target, banner + fs.readFileSync(source, 'utf8'));
console.log('Synced', path.relative(process.cwd(), target));
